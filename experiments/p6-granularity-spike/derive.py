#!/usr/bin/env python3
"""p6c1 spike — derive n=8 CONCRETE scenario YAMLs from the carter fixture.

THROWAWAY (experiments/** — not product code, not imported by cv_infra). It stands in
for what admission would eventually do (materialize-early); the spike only needs the
two arms to consume the SAME 8 concrete documents so that execution GRANULARITY is the
only variable (cycle-plan §2).

3 random axes, all uniform (cycle-plan §1): ``scenario.initial_pose`` ·
``scenario.goal`` · ``scenario.debug_obstacle``. Ranges are constants below; they were
CHOSEN (not measured) inside the warehouse lane the fixture documents as free, and
unreachable samples are acceptable — the metric is A-vs-B agreement, not pass rate.

PRNG: CPython ``random.Random`` (Mersenne Twister, stdlib). Determinism is pinned by
``DERIVE_SEED`` + a fixed draw ORDER; the self-check below re-runs the generation into
a second directory and requires byte-identical output.

Usage::

    python3 derive.py --out scenarios [--sut-image-ref REF]
    python3 derive.py --self-check          # generate twice + parse; writes nothing final
"""

from __future__ import annotations

import argparse
import filecmp
import math
import random
import shutil
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE = REPO_ROOT / "tests" / "fixtures" / "nova_carter_warehouse_goal.yaml"

#: The one seed this spike's input set hangs on (changing it changes all 8 samples).
DERIVE_SEED = 20260825

#: Sample count (cycle-plan: n=8).
N_SAMPLES = 8

# --------------------------------------------------------------------------- #
# Uniform ranges — CHOSEN, not measured. Provenance of the frame they sit in:
# the fixture's own comments record the warehouse map extent
# x[-11.975, 12.03] y[-17.975, 20.83], the SUT's AMCL start pose (-6.0, -1.0, yaw=pi)
# and a pass-proven goal (-6.0, 5.0, yaw=pi/2) reached by "a short straight drive up
# the same lane". Everything below is a box around THAT lane.
#
# initial_pose stays a JITTER around the AMCL start pose on purpose: the SUT is a
# blackbox whose localization initialises itself at (-6, -1, pi) (REQ-EXEC-005 — we
# do not edit the SUT), so teleporting the robot far away would not randomise the
# scenario, it would only break localisation for every sample identically.
# --------------------------------------------------------------------------- #
INITIAL_POSE_X_RANGE = (-6.6, -5.4)  # AMCL start x=-6.0 +/- 0.6 m
INITIAL_POSE_Y_RANGE = (-1.6, -0.4)  # AMCL start y=-1.0 +/- 0.6 m
INITIAL_POSE_YAW_RANGE = (math.pi - 0.30, math.pi + 0.30)  # AMCL start yaw=pi +/- 0.3 rad

GOAL_X_RANGE = (-7.5, -4.5)  # the lane, +/- 1.5 m around x=-6
GOAL_Y_RANGE = (1.5, 6.5)  # up the lane (pass-proven goal y=5.0 sits inside)
GOAL_YAW_RANGE = (-math.pi, math.pi)  # free heading at the goal

# Low cuboid (runner default height 0.15 m -> below the 2D-lidar scan plane, so the
# blackbox nav cannot see it): where it lands decides whether a sample collides.
OBSTACLE_X_RANGE = (-7.0, -5.0)
OBSTACLE_Y_RANGE = (0.0, 4.0)

#: Rounding of the drawn floats — the YAML is the input document a human reads and
#: diffs; 4 decimals is ~0.1 mm / 0.006 deg, far below anything the sim resolves.
DECIMALS = 4

HEADER = """\
# GENERATED by experiments/p6-granularity-spike/derive.py — DO NOT EDIT.
#
# p6c1 job-granularity spike input: one CONCRETE sample of the carter scenario
# (3 uniform axes: initial_pose / goal / debug_obstacle). Both arms consume this
# same document, so execution granularity is the only variable.
#   derive seed : {seed}
#   sample      : {index} of {total}
#   PRNG        : CPython random.Random (Mersenne Twister), python {py}
#   base        : tests/fixtures/nova_carter_warehouse_goal.yaml
"""


def draw_samples(seed: int, total: int) -> list[dict]:
    """Draw ``total`` samples in a FIXED order (the order IS part of the pin)."""
    rng = random.Random(seed)
    samples = []
    for _ in range(total):
        sample = {
            "initial_pose": {
                "x": rng.uniform(*INITIAL_POSE_X_RANGE),
                "y": rng.uniform(*INITIAL_POSE_Y_RANGE),
                "yaw": rng.uniform(*INITIAL_POSE_YAW_RANGE),
            },
            "goal": {
                "x": rng.uniform(*GOAL_X_RANGE),
                "y": rng.uniform(*GOAL_Y_RANGE),
                "yaw": rng.uniform(*GOAL_YAW_RANGE),
            },
            "debug_obstacle": {
                "x": rng.uniform(*OBSTACLE_X_RANGE),
                "y": rng.uniform(*OBSTACLE_Y_RANGE),
            },
        }
        samples.append(_round(sample))
    return samples


def _round(block: dict) -> dict:
    return {k: {kk: round(vv, DECIMALS) for kk, vv in v.items()} for k, v in block.items()}


def _fixture_text() -> str:
    return FIXTURE.read_text(encoding="utf-8")


def _fixture_tail(text: str) -> str:
    """Everything from the ``sut:`` block down — copied VERBATIM from the fixture.

    Only the ``scenario:`` block is re-authored (that is where the 3 axes live); the
    SUT pin, adapter_config and acceptance_criteria ride unchanged so the spike is
    comparing execution granularity, not a re-typed scenario.
    """
    marker = "\nsut:\n"
    idx = text.index(marker)
    return text[idx + 1 :]


def render(index: int, total: int, sample: dict, seed: int, sut_image_ref: str | None) -> str:
    text = _fixture_text()
    tail = _fixture_tail(text)
    if sut_image_ref is not None:
        tail = _repin_sut(tail, sut_image_ref)
    header = HEADER.format(
        seed=seed,
        index=index,
        total=total,
        py="{}.{}.{}".format(*sys.version_info[:3]),
    )
    ip, goal, obs = sample["initial_pose"], sample["goal"], sample["debug_obstacle"]
    scenario = f"""
apiVersion: cv-infra/v1

scenario:
  scene: nova_carter_warehouse
  robot: nova_carter
  initial_pose:
    x: {ip["x"]}
    y: {ip["y"]}
    yaw: {ip["yaw"]}
  goal:
    x: {goal["x"]}
    y: {goal["y"]}
    yaw: {goal["yaw"]}
    frame: map
  debug_obstacle:
    x: {obs["x"]}
    y: {obs["y"]}
  seed: 42
  timeout_s: 120

"""
    return header + scenario + tail


def _repin_sut(tail: str, sut_image_ref: str) -> str:
    """Rebuild the whole ``sut:`` block around ``sut_image_ref``.

    The fixture's block carries several lines of PROSE about the digest it pins. If
    only the value were swapped, that prose would describe a different image than the
    one on the line below it (G-79 — the string that survives a change and lies). So
    the block is replaced entirely, comment included, and says where its value came
    from instead.
    """
    lines = tail.splitlines(keepends=True)
    start = next(i for i, line in enumerate(lines) if line.startswith("sut:"))
    ref_idx = next(i for i, line in enumerate(lines) if line.startswith("  image_ref:"))
    block = (
        "sut:\n"
        "  # SPIKE RE-PIN (derive.py --sut-image-ref): the fixture's digest is not the\n"
        "  # one this measurement host holds locally, and pulling a ~3 GB SUT from GHCR\n"
        "  # is out of the spike's scope (read-only reuse of images already present).\n"
        "  # The value below is the digest THIS host's production carter jobs ran with.\n"
        f"  image_ref: {sut_image_ref}\n"
    )
    return "".join(lines[:start]) + block + "".join(lines[ref_idx + 1 :])


def generate(out_dir: Path, seed: int, total: int, sut_image_ref: str | None) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for i, sample in enumerate(draw_samples(seed, total), start=1):
        path = out_dir / f"sample_{i:02d}.yaml"
        path.write_text(render(i, total, sample, seed, sut_image_ref), encoding="utf-8")
        written.append(path)
    return written


def parse_check(paths: list[Path]) -> None:
    """Every generated document must be an ADMISSIBLE VerificationRequest (M1 loader)."""
    sys.path.insert(0, str(REPO_ROOT))
    from cv_infra.contract.loader import load_request  # noqa: PLC0415

    for path in paths:
        admitted = load_request(path)
        req = admitted.request
        print(
            f"[derive] {path.name}: OK  initial_pose=({req.scenario.initial_pose.x}, "
            f"{req.scenario.initial_pose.y}, {req.scenario.initial_pose.yaw}) "
            f"goal=({req.scenario.goal.x}, {req.scenario.goal.y}, {req.scenario.goal.yaw}) "
            f"obstacle=({req.scenario.debug_obstacle.x}, {req.scenario.debug_obstacle.y}) "
            f"seed={req.scenario.seed} criteria={len(req.acceptance_criteria)}"
        )


def self_check(seed: int, total: int, sut_image_ref: str | None) -> int:
    """Generate twice into throwaway dirs; require byte-identical output + parse OK."""
    with tempfile.TemporaryDirectory() as tmp:
        a, b = Path(tmp) / "a", Path(tmp) / "b"
        paths_a = generate(a, seed, total, sut_image_ref)
        generate(b, seed, total, sut_image_ref)
        match, mismatch, errors = filecmp.cmpfiles(a, b, [p.name for p in paths_a], shallow=False)
        print(f"[derive] self-check: identical={len(match)} differing={mismatch} errors={errors}")
        if mismatch or errors:
            return 1
        parse_check(paths_a)
    print(f"[derive] self-check PASSED (2 runs x {total} files, byte-identical, all admissible)")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(Path(__file__).parent / "scenarios"))
    ap.add_argument("--seed", type=int, default=DERIVE_SEED)
    ap.add_argument("--n", type=int, default=N_SAMPLES)
    ap.add_argument(
        "--sut-image-ref",
        default=None,
        help="override the fixture's sut.image_ref (spike hosts hold their own digest)",
    )
    ap.add_argument("--self-check", action="store_true")
    args = ap.parse_args(argv)

    if args.self_check:
        return self_check(args.seed, args.n, args.sut_image_ref)

    out_dir = Path(args.out)
    if out_dir.exists():
        shutil.rmtree(out_dir)
    paths = generate(out_dir, args.seed, args.n, args.sut_image_ref)
    parse_check(paths)
    print(f"[derive] wrote {len(paths)} scenario(s) to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
