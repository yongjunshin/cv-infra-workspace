"""QA cross-cutting guard — every document the PLATFORM ITSELF supplies must
(a) satisfy the runner's UNCONDITIONAL preconditions and (b) ride the REAL M1
admit path. Parameterized over a DOCUMENT-SOURCE REGISTRY (G-70).

WHY PARAMETERIZED (the measured failure, p5c15): the same class of defect —
a self-supplied request that declares ``reached_goal`` ALONE, so the runner's
unconditional ``telemetry.bind()`` raises before the readiness barrier — had a
guard already (``test_fixture_canonical_guard``), and that guard looked at
``tests/fixtures/*.yaml`` ONLY. When a SECOND document source appeared (the
built-in self-test stub, ``cv_infra/orchestrator/selftest.py``) the defect came
back untouched. A per-source hand-written guard re-buys the same lesson every
time an input source is added; a registry makes the next source declare itself
or fail ``test_every_document_source_is_registered``.

WHY (b) IS HERE AT ALL: p5c15 also measured that NOTHING locked "the submission
actually traverses M1 admit" — a bypass branch could be planted and the whole
suite stayed green. (a) alone is therefore not enough: a document can satisfy
every precondition and still be admitted by a shortcut that proves nothing about
the path a consumer request takes (``REQ-SELFTEST-002`` 경로 동일성).

HOW EACH PROPERTY IS MADE NON-VACUOUS (G-35) — both controls live in-file, so
every registered source carries its own proof of sensitivity:
  * (a) the same document with its ``no_collision`` criterion stripped MUST fail
    the replay (that is the exact p5c15 shape);
  * (b) the same document with one poison key MUST be refused BY NAME, while the
    clean document MUST be accepted through the same production path.

NOT RETYPED: the (a) predicate is the runner's own code — this file builds the
sampler exactly as ``runner/main.py`` does and calls the REAL
``PhysicsTelemetrySampler.bind``; the platform's own ``RuntimeError`` is the
failure signal. Reaching the GPU-only ``omni`` import means the precondition held.

QA-owned cross-cutting test (decision 2026-06-25-tests-ownership) — implementation
teams do not edit this file.
"""

